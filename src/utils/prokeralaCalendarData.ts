/**
 * Retrieve exact Prokerala calendar day data for any Date.
 */
export function getProkeralaDayData(date: Date): ProkeralaDayRecord | null {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = date.getDate();
  const key = `${y}-${m}`;
  const monthData = PROKERALA_MONTHS[key];
  if (!monthData) return null;
  return monthData.days.find((item) => item.gregorianDay === d) || null;
}

/**
 * Retrieve month metadata from Prokerala database
 */
export function getProkeralaMonthData(year: number, monthIndex: number): ProkeralaMonthData | null {
  const m = String(monthIndex + 1).padStart(2, "0");
  const key = `${year}-${m}`;
  return PROKERALA_MONTHS[key] || null;
}
